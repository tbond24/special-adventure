  await first.locator('[data-add-unit-option=amenity]').click();
  await first.locator('.unit-custom-amenities input').fill('Rooftop terrace');
  await first.locator('.unit-utilities summary').click();
  await first.locator('[data-add-unit-option=utility]').click();
  await first.locator('.unit-custom-utilities input').fill('Solar power');
  await first.locator('.unit-rules summary').click();
