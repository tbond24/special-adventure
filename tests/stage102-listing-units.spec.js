  const imageStyle=await form.locator('.unit-draft-preview img').first().evaluate(img=>({ratio:getComputedStyle(img).aspectRatio,fit:getComputedStyle(img).objectFit}));
  expect(imageStyle).toEqual({ratio:'4 / 3',fit:'cover'});
