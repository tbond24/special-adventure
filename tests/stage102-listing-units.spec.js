  await expect.poll(()=>first.locator('img').count()).toBeGreaterThanOrEqual(3);
  await first.locator('.duplicate-unit-menu summary').click();
  await first.locator('.duplicate-same-property').click();
  await expect(form.locator('.unit-editor')).toHaveCount(2);
  const second=form.locator('.unit-editor').nth(1);
  await expect(second.locator('.unit-name-input')).toHaveValue('Flamingo A1 (copy)');
  await expect(second.locator('[data-base-name=roomName]')).toHaveValue(originalTitle);
  await second.locator('.duplicate-unit-menu summary').click();
  await second.locator('.duplicate-same-property').click();
  await expect(form.locator('.unit-editor')).toHaveCount(3);
  const third=form.locator('.unit-editor').nth(2);
  await expect(third.locator('.unit-name-input')).toHaveValue('Flamingo A1 (copy) (copy)');
  await third.locator('.unit-name-input').fill('Flamingo A3');
